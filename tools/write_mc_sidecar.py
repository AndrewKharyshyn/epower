#!/usr/bin/env python3
"""M399 (audit F25): energy_uncertainty_mc.json is generated from the live release object summary_arrays.json energyUncertaintyMC (never from a separate
run), so it cannot disagree with the dashboard payload. Idempotent. Usage: python tools/write_mc_sidecar.py [--dry-run] [--check]"""
import json, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
PROV = "GENERATED by tools/write_mc_sidecar.py from summary_arrays.json energyUncertaintyMC (the release object). Do not hand-edit; regenerate."


def build(arrays):
    out = {"_provenance": PROV}
    out.update(arrays["energyUncertaintyMC"])
    return out


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    os.chdir(ROOT)
    A = json.load(open("summary_arrays.json", encoding="utf-8"))
    text = json.dumps(build(A), indent=1, ensure_ascii=False)
    cur = open("energy_uncertainty_mc.json", encoding="utf-8").read() if os.path.exists("energy_uncertainty_mc.json") else None
    same = cur == text
    if "--check" in argv:
        print("sidecar matches the payload" if same else "sidecar DIFFERS from the payload")
        return 0 if same else 1
    if not same and "--dry-run" not in argv:
        with open("energy_uncertainty_mc.json", "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(json.dumps({"written": (not same) and "--dry-run" not in argv}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
