#!/usr/bin/env python3
"""M423 (analyses/M423_spec.md): ingestion refresh of the additive block summary_arrays.json['exposureBasis'] (+ its artifact stamp). The block was spliced once at M415 from two control builds; its populations, the
rated-over-legacy factor, the legacy-basis disclosure values, the rated point beside the Monte Carlo and the primary exposure depend on the corpus, and no ingestion stage refreshed them (found by the M422 rehearsal).

No second arrays build is needed: the legacy-basis values are recomputed from drive_master.csv alone with the released builders on the legacy exposure frame (tools/exposure_frame.py), exactly as the arrays build computes
them on the legacy basis - _metric_convention, category_A (cycleByType, cycleCumulative), _crate_axes, _crate_ref_lines - and the per-speed rows of cycleBySpeed are derived from the rated payload rows
(rate = kWh / CAP_KWH / km x 100 from the stored one-decimal kWh and km; the raw-pass accumulators are not re-run). The rated side is the payload itself (it was built on the rated basis). The block is assembled by
tools/exposure_splice.build_block (the M415 code), so on an unchanged corpus the refreshed block equals the published one (tests/synthetic/test_exposure_basis_refresh.py).
Writes ONLY /exposureBasis and /_artifactStamps/exposureBasis. Usage: python tools/exposure_basis_refresh.py [--dry-run]"""
import copy, datetime, hashlib, json, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
os.chdir(ROOT); sys.path.insert(0, ROOT); sys.path.insert(0, os.path.join(ROOT, "tools"))
import pandas as pd
import compute_summary_arrays as C
import exposure_frame as EF
import exposure_splice as ES

ALLOWED = ["/exposureBasis", "/_artifactStamps/exposureBasis"]


def legacy_values(dm, payload):
    """The 'build A' keys build_block reads, computed on the legacy exposure frame; cycleBySpeed derived from the rated rows of the payload."""
    dml = EF.exposure_frame(dm, "legacy2p1kWh")
    cat = C.category_A(dml, None)
    rated_rows = payload["cycleBySpeed"]
    cbs = [{"zone": r["zone"], "rate": round(r["kwh"] / C.CAP_KWH / r["km"] * 100, 1), "kwh": r["kwh"], "km": r["km"], "color": r["color"]} for r in rated_rows]
    pts = C._crate_axes(dml, payload)
    return {"meta": {"gtcSum": round(float(dml["gtc"].sum()), 1), "fceSum": round(float(dml["fce"].sum()), 1)},
            "metricConvention": C._metric_convention(dml), "cycleByType": cat["cycleByType"], "cycleBySpeed": cbs,
            "cycleCumulative": cat.get("cycleCumulative"), "cRateAxes": pts[-1], "cRateRefLines": C._crate_ref_lines(dml, payload)}


def build(dm, payload):
    A = json.loads(json.dumps(legacy_values(dm, payload), default=float))
    blk = ES.build_block(A, payload, payload)
    blk["_provenance"] = blk["_provenance"].replace("GENERATED by tools/exposure_splice.py (M415,", "GENERATED by tools/exposure_splice.py (M415) and refreshed at every ingestion by tools/exposure_basis_refresh.py (M423; legacy values recomputed from the master, no second arrays build;", 1)
    return blk


def splice(P, blk, md5, now=None):
    new = copy.deepcopy(P)
    old = P.get("exposureBasis")
    new["exposureBasis"] = blk
    st = copy.deepcopy(P["_artifactStamps"]["fuelContract"])
    st.update(corpusHash=md5, generatedAt=now or datetime.datetime.now(datetime.timezone.utc).isoformat(), computationStatus="computed",
              computationStatusNote="M423: refreshed by tools/exposure_basis_refresh.py (legacy-basis disclosure values recomputed from the master with the released builders; rated side = this payload); exposure basis tags, populations, factor",
              upstreamHashes={"driveMasterMd5": md5})
    for k in ("carriedForward", "basisNDrives", "carriedFromMaster", "carryForwardNote", "reissuedFrom", "reissueNote", "supersededCarryNote", "carriedBlocks", "includedInReleaseAt", "computedAt", "computedAtNote", "inputBasis"):
        st.pop(k, None)
    new["_artifactStamps"]["exposureBasis"] = st
    changed = ([] if old == blk else ["/exposureBasis"]) + ["/_artifactStamps/exposureBasis"]
    bad = [c for c in changed if c not in ALLOWED]
    return new, changed, bad


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    dm = pd.read_csv("drive_master.csv", low_memory=False)
    raw = open("summary_arrays.json", "r", encoding="utf-8", newline="").read()
    P = json.loads(raw)
    blk = build(dm, P)
    md5 = hashlib.md5(open("drive_master.csv", "rb").read()).hexdigest()
    new, changed, bad = splice(P, blk, md5)
    old = P.get("exposureBasis") or {}
    diff = sorted(k for k in blk if k != "_provenance" and blk[k] != old.get(k))
    print(json.dumps({"changed": changed, "outsideAllowList": bad, "topLevelKeysChanged": diff, "nDrives": blk["populations"]["allDrivesWithAhValue"]["nDrives"], "factor": blk["factor"]["aggregateRatedOverLegacy"]}, indent=1))
    if bad:
        return 1
    if "--dry-run" not in argv:
        with open("summary_arrays.json", "w", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(new, ensure_ascii=False, indent=1) + ("\n" if raw.endswith("\n") else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
