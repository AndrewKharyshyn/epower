#!/usr/bin/env python3
"""M488 (audit Update 7, A02): the additive payload block `highwaySessionGtc`: the gross turnover cycles (GTC, rated 5 Ah reference) of the declared highway-session dates, summed over EXPLICIT inclusive calendar dates on the
unrounded per-drive Ah ledger (ah_throughput.csv: ah_throughput / CAP_AH_RATED), plus its share of the corpus GTC on the same ledger. It replaces a dashboard subtraction of two rounded cumulative-ledger end points that
dropped the first day of the Jun 9-14 session. Nothing is typed except the declared date sets (a curated ledger, below); every number comes from ah_throughput.csv.
Usage: python tools/highway_session_gtc.py [--dry-run]   (writes ONLY /highwaySessionGtc and /_artifactStamps/highwaySessionGtc of summary_arrays.json)"""
import copy, datetime, hashlib, json, os, sys

import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tools"))
from exposure_frame import CAP_AH_RATED

METHOD_VERSION = 1
ALLOWED = ["/highwaySessionGtc", "/_artifactStamps/highwaySessionGtc"]
DP = 6
# Declared highway-session dates (inclusive, calendar dates of the logged corpus). The dashboard narrative names these three sessions; the dates are the declaration, the numbers are computed.
SESSIONS = [
    {"id": "jun09_14", "label": "Jun 9-14", "dates": ["2026-06-09", "2026-06-10", "2026-06-11", "2026-06-12", "2026-06-13", "2026-06-14"]},
    {"id": "jun19", "label": "Jun 19", "dates": ["2026-06-19"]},
    {"id": "jun21", "label": "Jun 21", "dates": ["2026-06-21"]},
]


def daily_gtc(ah):
    """Unrounded GTC per calendar date: sum of ah_throughput over the drives of the date / CAP_AH_RATED (missing Ah contributes nothing and is not zero-filled into counts)."""
    g = ah.dropna(subset=["ah_throughput"]).groupby("date")["ah_throughput"].sum() / CAP_AH_RATED
    return {str(k): float(v) for k, v in g.items()}


def build(ah, sessions=None):
    sessions = SESSIONS if sessions is None else sessions
    d = daily_gtc(ah)
    declared = [x for s in sessions for x in s["dates"]]
    assert len(declared) == len(set(declared)), "a date is declared in two sessions"
    missing = [x for x in declared if x not in d]
    per_sess = []
    for s in sessions:
        vals = [d[x] for x in s["dates"] if x in d]
        per_sess.append({"id": s["id"], "label": s["label"], "dates": s["dates"], "nDates": len(s["dates"]), "nDatesWithLedger": len(vals), "gtc": round(sum(vals), DP)})
    total = sum(d[x] for x in declared if x in d)
    corpus = sum(d.values())
    return {
        "_provenance": "GENERATED by tools/highway_session_gtc.py (M488, audit Update 7 A02); do not hand-edit. Additive block, regenerated at every ingestion.",
        "methodVersion": METHOD_VERSION,
        "basis": "rated5Ah", "capAhRated": CAP_AH_RATED,
        "source": "ah_throughput.csv: per-drive ah_throughput / CAP_AH_RATED, summed per calendar date, unrounded; the declared date sets are inclusive and listed per session",
        "sessions": per_sess,
        "declaredDates": declared, "nDeclaredDates": len(declared), "missingDates": missing,
        "perDay": {x: round(d[x], DP) for x in declared if x in d},
        "totalGtc": round(total, DP), "corpusGtc": round(corpus, DP), "sharePct": round(total / corpus * 100, 4) if corpus > 0 else None,
        "reading": ["the session totals sum the explicit inclusive dates; no cumulative end point is subtracted",
                    "GTC is estimated from the logged current with the rated 5 Ah documentary reference (verified:false); a project-specific throughput metric, not a rated cycle life"]}


def splice(A, blk, master_md5, now=None):
    import dependence_sensitivity as DS
    new = copy.deepcopy(A)
    new["highwaySessionGtc"] = blk
    old = (A.get("_artifactStamps") or {}).get("highwaySessionGtc")
    if old and A.get("highwaySessionGtc") == blk and old.get("corpusHash") == master_md5:
        new["_artifactStamps"]["highwaySessionGtc"] = old
    else:
        st = copy.deepcopy(A["_artifactStamps"]["cohortSupport"])
        st.update(corpusHash=master_md5, generatedAt=(now or datetime.datetime.now(datetime.timezone.utc)).isoformat(), computationStatus="computed",
                  computationStatusNote="M488: derived by tools/highway_session_gtc.py from ah_throughput.csv (explicit inclusive dates, unrounded Ah); additive block", upstreamHashes={"driveMasterMd5": master_md5})
        st.pop("carriedForward", None)
        st["includedInReleaseAt"] = st["computedAt"] = st["generatedAt"]
        st["inputBasis"] = {"nDrives": A["meta"]["totalDrives"], "masterMd5": master_md5, "source": "stamping pass: meta.totalDrives, corpusHash"}
        new["_artifactStamps"]["highwaySessionGtc"] = st
    ch = DS._paths(A, new)
    return new, ch, [c for c in ch if not any(c == a_ or c.startswith(a_ + "/") for a_ in ALLOWED)]


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    os.chdir(ROOT)
    ah = pd.read_csv("ah_throughput.csv", low_memory=False)
    blk = build(ah)
    if blk["missingDates"]:
        print(json.dumps({"error": "declared dates without an Ah ledger entry", "missingDates": blk["missingDates"]}))
        return 1
    raw = open("summary_arrays.json", "r", encoding="utf-8", newline="").read()
    A = json.loads(raw)
    md5 = hashlib.md5(open("drive_master.csv", "rb").read()).hexdigest()
    new, changed, bad = splice(A, blk, md5)
    print(json.dumps({"nChanged": len(changed), "outsideAllowList": bad, "totalGtc": blk["totalGtc"], "corpusGtc": blk["corpusGtc"], "sharePct": blk["sharePct"], "sessions": [(s["label"], s["gtc"]) for s in blk["sessions"]]}))
    if bad:
        return 1
    if "--dry-run" not in argv and changed:
        with open("summary_arrays.json", "w", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(new, ensure_ascii=False, indent=1) + ("\n" if raw.endswith("\n") else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
