#!/usr/bin/env python3
"""PCL-1 (spec analyses/PCL1_spec.md section 2): deterministic polling-arm schedule.
Design A (preferred): for every calendar day from the START DATE the trips are numbered 1, 2, ... in order of their start; consecutive pairs (1,2), (3,4), ... form a block holding one 'fast' and one 'slow' trip in a seeded random order; the arm of an
unpaired last trip is the slot-1 arm of its block. The arm of a block depends only on (seed, date, block), so the schedule does not depend on how many trips a day has.
Design B (fallback, fixed before the START DATE): half-day arms. Days are taken in consecutive pairs from the START DATE; a seeded draw decides which day of a pair has the fast arm in the morning (start before 13:00 local); the afternoon arm is the opposite.
Usage: python tools/pcl_schedule.py --start YYYY-MM-DD [--design A|B] [--days 200] [--max-trips 12] [--seed 42] [--out analyses/PCL1_schedule.csv]"""
import argparse
import datetime as dt
import hashlib
import os
import sys

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ARMS = ("fast", "slow")
BOUNDARY = "13:00"


def block_arms(seed, date, block):
    """(arm of the first trip of the block, arm of the second trip) for one (seed, date, block)."""
    key = [int(seed), int(date.strftime("%Y%m%d")), int(block)]
    first = int(np.random.default_rng(key).integers(0, 2))
    return ARMS[first], ARMS[1 - first]


def arm_for(seed, date, trip_index):
    """Design A: assigned arm of trip number trip_index (1-based) on a calendar date."""
    block = (trip_index + 1) // 2
    a, b = block_arms(seed, date, block)
    return a if trip_index % 2 == 1 else b


def arm_halfday(seed, start, date, period):
    """Design B: assigned arm of the half-day 'AM' (start before 13:00 local) or 'PM' of a date."""
    k = (date - start).days
    draw = int(np.random.default_rng([int(seed), 9, k // 2]).integers(0, 2))
    am_fast = (draw == k % 2)
    am = ARMS[0] if am_fast else ARMS[1]
    return am if period == "AM" else (ARMS[1] if am == ARMS[0] else ARMS[0])


def period_of(time_start):
    """'AM' if the local start time (HH:MM...) is before 13:00, else 'PM'."""
    return "AM" if str(time_start)[:5] < BOUNDARY else "PM"


def build(start, days, max_trips, seed, design="A"):
    rows = []
    for k in range(days):
        d = start + dt.timedelta(days=k)
        if design == "A":
            for t in range(1, max_trips + 1):
                rows.append((d.isoformat(), t, (t + 1) // 2, arm_for(seed, d, t)))
        else:
            for p in ("AM", "PM"):
                rows.append((d.isoformat(), p, p, arm_halfday(seed, start, d, p)))
    return rows


def write(path, start, days, max_trips, seed, design="A"):
    rows = build(start, days, max_trips, seed, design)
    body = "date,slot,block,arm\n" + "".join("%s,%s,%s,%s\n" % r for r in rows)
    head = "# PCL-1 schedule (spec analyses/PCL1_spec.md section 2). START DATE %s; seed %d; design %s; %d days x %s; generated by tools/pcl_schedule.py\n" % (
        start.isoformat(), seed, design, days, ("%d trips" % max_trips) if design == "A" else "2 half-days")
    head += "# body sha256 %s\n" % hashlib.sha256(body.encode("utf-8")).hexdigest()
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(head + body)
    return rows


def read(path):
    """(start date, seed, design, {(date, slot): arm}, body sha256) of a schedule file; slot = trip number (design A) or 'AM' / 'PM' (design B)."""
    start, seed, design, table, sha = None, None, "A", {}, None
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line.startswith("# PCL-1 schedule"):
                start = dt.date.fromisoformat(line.split("START DATE ")[1].split(";")[0])
                seed = int(line.split("seed ")[1].split(";")[0])
                if "design " in line:
                    design = line.split("design ")[1].split(";")[0].strip()
            elif line.startswith("# body sha256"):
                sha = line.split("sha256 ")[1].strip()
            elif line and not line.startswith("#") and not line.startswith("date,"):
                d, t, b, a = line.split(",")
                table[(d, int(t) if design == "A" else t)] = a
    return start, seed, design, table, sha


def assigned_arm(design, table, date, trip, time_start):
    """Assigned arm of a logged drive (date string, trip number by start order, local start time)."""
    return table.get((date, trip if design == "A" else period_of(time_start)), "unscheduled")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--start", required=True)
    ap.add_argument("--design", choices=("A", "B"), default="A")
    ap.add_argument("--days", type=int, default=200)
    ap.add_argument("--max-trips", type=int, default=12)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", default=os.path.join(ROOT, "analyses", "PCL1_schedule.csv"))
    a = ap.parse_args(argv)
    write(a.out, dt.date.fromisoformat(a.start), a.days, a.max_trips, a.seed, a.design)
    print("wrote %s" % a.out)


if __name__ == "__main__":
    sys.exit(main())
