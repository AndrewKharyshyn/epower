#!/usr/bin/env python3
"""Day-clustered percentile bootstrap of a ratio of sums, from per-day sufficient statistics (M383, audit F22).

The former loop rebuilt a DataFrame per draw (pd.concat of the sampled days) and re-summed it. For an additive ratio  sum(num) / sum(den)  the
resample only needs the per-day totals: draw the same day indices, add the per-day sums, divide. The estimator, the resampling unit (calendar
day), the percentile CI, the seed and the draw count are unchanged; the per-draw rng.choice calls are kept (same stream as the former loop).
Only valid for additive ratios; medians, refits and event reconstruction need their own algorithms.
Day order = order of first appearance (DataFrame.date.unique()), exactly as the former dayboot()."""
import numpy as np


def ratio_boot_ci_detail(df, num, den, scale=1.0, nb=4000, seed=42, day_col="date", q=(2.5, 97.5), nan="raise"):
    """(CI, n_draws_used). Input semantics (M401, audit N04): an empty frame, a non-finite value (NaN with nan="raise", inf always) raises ValueError naming the column; nan="skipna" reproduces
    the former per-column pandas sum (a NaN contributes 0 to its own column). A draw whose resampled denominator total is 0 or non-finite is EXCLUDED and counted (n_draws_used < nb);
    if every draw is invalid the CI is [nan, nan]. The rng stream, estimator, seed and draw count are unchanged: finite data give the same CI as before."""
    if nan not in ("raise", "skipna"):
        raise ValueError("nan must be 'raise' or 'skipna'")
    if len(df) == 0:
        raise ValueError("ratio_boot_ci: empty frame (no days to resample)")
    nu, de = _col(df, num, nan == "skipna"), _col(df, den, nan == "skipna")
    for name, v in ((num, nu), (den, de)):
        if np.isinf(v).any():
            raise ValueError("ratio_boot_ci: infinite value in column %r" % (name,))
        if np.isnan(v).any():
            raise ValueError("ratio_boot_ci: non-finite (NaN) value in column %r (%d rows); pass nan='skipna' to reproduce the former pandas skip-NaN sum" % (name, int(np.isnan(v).sum())))
    days = df[day_col].unique()
    code = {d: i for i, d in enumerate(days)}
    di = df[day_col].map(code).to_numpy()
    nd = len(days)
    sn = np.bincount(di, weights=nu, minlength=nd)
    sd = np.bincount(di, weights=de, minlength=nd)
    rng = np.random.default_rng(seed)
    pick = np.stack([rng.choice(nd, nd) for _ in range(nb)])
    dtot = sd[pick].sum(axis=1)
    ok = (dtot != 0) & np.isfinite(dtot)
    if not ok.any():
        return [float("nan"), float("nan")], 0
    out = scale * sn[pick].sum(axis=1)[ok] / dtot[ok]
    return [float(np.percentile(out, q[0])), float(np.percentile(out, q[1]))], int(ok.sum())


def ratio_boot_ci(df, num, den, scale=1.0, nb=4000, seed=42, day_col="date", q=(2.5, 97.5), nan="raise"):
    """Percentile CI [lo, hi] of scale * sum(df[num]) / sum(df[den]) under day-clustered resampling. num / den: column name or (name, name) sum. See ratio_boot_ci_detail for the input semantics."""
    return ratio_boot_ci_detail(df, num, den, scale, nb, seed, day_col, q, nan)[0]


def _col(df, c, skipna=False):
    parts = [df[x].to_numpy(dtype=float) for x in (c if isinstance(c, (tuple, list)) else (c,))]
    if skipna:
        parts = [np.where(np.isnan(p), 0.0, p) for p in parts]
    return sum(parts[1:], parts[0].copy())


def ols_boot_slopes(X, y, days, coef=1, nb=4000, seed=42, t=None, min_unique_t=3, cond_max=1e9):
    """M492 (audit Update 7, optimisation): day-clustered bootstrap of one OLS coefficient from per-day sufficient statistics. The former loops rebuilt the sampled row index and refit by lstsq for every draw
    (rng.choice(uniq, size=len(uniq), replace=True) -> concatenated row indexes -> np.linalg.lstsq). The refit only needs X'X and X'y of the resample, and those are sums of per-day blocks weighted by how often each day was
    drawn: the draws are generated by the SAME per-draw rng.choice calls (same stream), turned into day multiplicities, and each draw solves the p x p normal equations. `days`: per-row day labels (np.unique order is the draw
    order, as before); `t`: per-row regressor whose number of distinct values among the resampled rows must be >= min_unique_t (the former skip rule; default = the coefficient column of X); a draw that skipped the former loop
    consumed its random numbers and is skipped here too.
    Numerical guard: columns are scaled to unit RMS before forming the normal equations; a draw whose scaled X'X has a condition number above cond_max (rank-deficient resamples, a dummy column with no drawn row) is
    refitted with the former lstsq on the rebuilt rows, so min-norm behaviour is unchanged; a failing lstsq skips the draw exactly as the former try/except. Returns the array of coefficients in draw order (skipped draws absent)
    and the number of draws that used the lstsq fallback."""
    X = np.asarray(X, float)
    y = np.asarray(y, float)
    uniq, di = np.unique(np.asarray(days), return_inverse=True)
    G = len(uniq)
    tt = X[:, coef] if t is None else np.asarray(t, float)
    scale = np.sqrt((X ** 2).mean(axis=0))
    scale[scale == 0] = 1.0
    Xs = X / scale
    p = X.shape[1]
    A = np.zeros((G, p, p))
    B = np.zeros((G, p))
    for g in range(G):
        r = di == g
        A[g] = Xs[r].T @ Xs[r]
        B[g] = Xs[r].T @ y[r]
    A2, B2 = A.reshape(G, p * p), B
    tvals, tcode_row = np.unique(tt, return_inverse=True)
    tcode = np.full(G, -1)
    for g in range(G):
        tcode[g] = tcode_row[di == g][0]                  # t is a function of the day (months from the date): one code per day
    assert all(len(set(tcode_row[di == g])) == 1 for g in range(G)), "t must be constant within a day"
    T01 = np.zeros((G, len(tvals)))
    T01[np.arange(G), tcode] = 1.0
    rng = np.random.default_rng(seed)
    out, fallback = [], 0
    CH = 500                                                # draws per chunk: the draws are generated one rng.choice call at a time (stream unchanged)
    for s in range(0, nb, CH):
        m = min(CH, nb - s)
        pick = np.stack([rng.choice(G, G) for _ in range(m)])
        C = np.bincount((pick + G * np.arange(m)[:, None]).ravel(), minlength=m * G).reshape(m, G).astype(float)
        keep = ((C > 0).astype(float) @ T01 > 0).sum(axis=1) >= min_unique_t        # distinct t values among the drawn days
        XtX = (C @ A2).reshape(m, p, p)
        Xty = C @ B2
        cond = np.linalg.cond(XtX)
        good = keep & np.isfinite(cond) & (cond < cond_max)
        val = np.full(m, np.nan)
        if good.any():
            val[good] = np.linalg.solve(XtX[good], Xty[good][..., None])[..., 0][:, coef] / scale[coef]
        for i in np.where(keep & ~good)[0]:
            fallback += 1
            idx = np.concatenate([np.where(di == g)[0] for g in pick[i]])
            try:
                val[i] = float(np.linalg.lstsq(X[idx], y[idx], rcond=None)[0][coef])
            except Exception:
                pass                                         # a failing lstsq skips the draw, as the former try / except
        out.extend(val[keep & np.isfinite(val)].tolist())
    return np.asarray(out), fallback
