#!/usr/bin/env python3
"""M721 (Director ruling, Andrii sign-off): the power-fade significance clause and two script-written specification counts.
Splices ONLY (a) the additive leaves nSpecsSpanZero / nSpecsExcludeZero into powerFade.cadenceSensitivity and fadeModes.power.trend.cadenceSensitivity (counted from the specification leaves already in the payload) and
(b) the significance clause inside powerFade.note and fadeModes.power.trend.note, regenerated by compute_summary_arrays._powerfade_sig_clause from the interval leaves. Any other difference STOPS.
Usage: python tools/m721_powerfade_wording_splice.py [--dry-run] [--check]"""
import json, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)
os.chdir(ROOT)
import compute_summary_arrays as C

P = "summary_arrays.json"
HEAD = "resistance trend. "
TAIL = " HV-current logging density, which changed"


def splice(A):
    changed, bad = [], []
    for name, h in (("powerFade", A["powerFade"]), ("fadeModes.power.trend", A["fadeModes"]["power"]["trend"])):
        cs = h["cadenceSensitivity"]
        if cs.get("status") == "ok":
            span = int(sum(1 for sp in cs["specs"] if sp["ci95"][0] <= 0.0 <= sp["ci95"][1]))
            for k, v in (("nSpecsSpanZero", span), ("nSpecsExcludeZero", int(cs["nSpecs"] - span))):
                if cs.get(k) != v:
                    cs[k] = v
                    changed.append("%s.cadenceSensitivity.%s" % (name, k))
        lo, hi = h["ci95MohmPerMo"]
        i = h["note"].find(HEAD)
        j = h["note"].find(TAIL)
        if i < 0 or j < i:
            bad.append(name + ".note: anchors not found")
            continue
        new_note = h["note"][:i + len(HEAD)] + C._powerfade_sig_clause(lo, hi, cs) + h["note"][j:]
        if new_note != h["note"]:
            h["note"] = new_note
            changed.append(name + ".note")
    allowed = {"powerFade.note", "fadeModes.power.trend.note"} | {"%s.cadenceSensitivity.%s" % (n, k) for n in ("powerFade", "fadeModes.power.trend") for k in ("nSpecsSpanZero", "nSpecsExcludeZero")}
    bad += [c for c in changed if c not in allowed]
    return A, changed, bad


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    raw = open(P, encoding="utf-8", newline="").read()
    A = json.loads(raw)
    A2, changed, bad = splice(json.loads(raw))
    if "--check" in argv:
        print(json.dumps({"check": "m721 powerFade wording", "alreadyApplied": not changed and not bad}))
        return 0 if not changed and not bad else 1
    print(json.dumps({"nChanged": len(changed), "changed": changed, "outsideAllowList": bad}, indent=1))
    if bad:
        return 1
    if "--dry-run" not in argv and changed:
        with open(P, "w", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(A2, ensure_ascii=False, indent=1) + (chr(10) if raw.endswith(chr(10)) else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
