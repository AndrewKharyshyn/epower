"""M415 method-change record (spec analyses/M413_spec.md Rev 3, gate (f); Director ruling additions): script-written, no typed numbers.
Compares the payload before the flip (git HEAD summary_arrays.json) with the flipped payload; lists old/new headline pairs, the reference-line drives, the risk-test before/after, every changed numeric leaf that carries a
95% interval and falls outside its previous interval, and a consistency check of the new cycleBySpeed Ah accumulator against the Ah sidecar.
Usage: python analyses/M415_method_change/build_record.py"""
import json, os, subprocess, sys
import pandas as pd
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
os.chdir(ROOT)
old = json.loads(subprocess.run(["git", "show", "HEAD:summary_arrays.json"], capture_output=True, text=True, encoding="utf-8", check=True).stdout)
new = json.load(open("summary_arrays.json", encoding="utf-8"))
SWITCHED = ("cycleByType", "cycleCumulative", "cycleBySpeed", "cycleBySpeedMeta", "metricConvention", "riskColdEngineBattery", "cRatePoints", "cRatePointsAK", "cRateRefLines", "cRateRefLinesAK", "cRateAxes", "records", "ledgerCrossCheck", "meta")


def pair(path):
    o, n = old, new
    for k in path:
        o, n = o[k], n[k]
    return {"path": "/".join(str(k) for k in path), "old": o, "new": n}


out = {"_provenance": "GENERATED by analyses/M415_method_change/build_record.py (M415); do not hand-edit"}
out["headlinePairs"] = [pair(p) for p in (("meta", "gtcSum"), ("meta", "fceSum"), ("metricConvention", "gtc"), ("metricConvention", "fce"), ("metricConvention", "efcStandard"), ("metricConvention", "gtcOverStandardEfc"),
                                         ("metricConvention", "fceOverStandardEfc"), ("metricConvention", "chargeDischargeRatio"), ("ledgerCrossCheck", "matchedAll", "ratio"), ("ledgerCrossCheck", "matchedAll", "excessPct"),
                                         ("ledgerCrossCheck", "matchedClean", "excessPct"), ("cRateAxes", "cPerA", "median"))]
out["metricConventionNewKeys"] = {k: new["metricConvention"][k] for k in new["metricConvention"] if k not in old["metricConvention"]}
out["cRateRefLines"] = {"old": old["cRateRefLines"]["lines"], "new": new["cRateRefLines"]["lines"],
                        "argmaxDriveChanged": {l_o["kind"]: (l_o.get("drive"), l_n.get("drive"), l_o.get("drive") != l_n.get("drive")) for l_o, l_n in zip(old["cRateRefLines"]["lines"], new["cRateRefLines"]["lines"]) if "drive" in l_o or "drive" in l_n}}
out["cycleByType"] = {"old": [{k: d[k] for k in ("label", "avg", "med")} for d in old["cycleByType"]], "new": [{k: d[k] for k in ("label", "avg", "med")} for d in new["cycleByType"]]}
rb_o, rb_n = old["riskColdEngineBattery"], new["riskColdEngineBattery"]
out["riskColdEngineBattery"] = {"old": rb_o.get("compare"), "new": rb_n.get("compare"), "oldColdPackChargeCrate": [rb_o.get("coldPackChargeCrateMed"), rb_o.get("coldPackChargeCrateMax")],
                                "newColdPackChargeCrate": [rb_n.get("coldPackChargeCrateMed"), rb_n.get("coldPackChargeCrateMax")]}
out["recordsChanged"] = [{"metric": o.get("metric"), "old": o.get("value"), "new": n.get("value")} for o, n in zip(old["records"], new["records"]) if json.dumps(o, sort_keys=True) != json.dumps(n, sort_keys=True)]
# changed numeric leaves with their own 95% interval that fall outside the previous interval
exceed = []


def walk(o, n, path):
    if isinstance(o, dict) and isinstance(n, dict):
        ci = o.get("ci95") or o.get("ci")
        if isinstance(ci, list) and len(ci) == 2:
            for k in ("est", "median", "bootMedian", "value", "slope", "mean"):
                if isinstance(o.get(k), (int, float)) and isinstance(n.get(k), (int, float)) and not (ci[0] <= n[k] <= ci[1]):
                    exceed.append({"path": "/".join(path + [k]), "old": o[k], "new": n[k], "oldCI95": ci})
        for k in o:
            if k in n:
                walk(o[k], n[k], path + [str(k)])
    elif isinstance(o, list) and isinstance(n, list) and len(o) == len(n):
        for i, (u, v) in enumerate(zip(o, n)):
            walk(u, v, path + [str(i)])


for k in SWITCHED:
    walk(old[k], new[k], [k])
out["changedLeavesOutsideOwnPreviousCI95"] = exceed
# cycleBySpeed Ah accumulator vs the sidecar (same drives; the zone sum covers the 1 Hz grid samples with speed, current and voltage all present)
sc = pd.read_csv("ah_throughput.csv")
tot = float(sc["ah_throughput"].sum())
zs = sum(d.get("ah", 0.0) for d in new["cycleBySpeed"])
zk = sum(d.get("kwh", 0.0) for d in new["cycleBySpeed"])
tk = float((sc["kwh_discharge"] + sc["kwh_charge"].abs()).sum())
out["cycleBySpeedAhConsistency"] = {"zoneAhSum": round(zs, 1), "sidecarAhSum": round(tot, 1), "ahRatioToSidecar": round(zs / tot, 4), "zoneKwhSum": round(zk, 1), "sidecarKwhSum": round(tk, 1), "kwhRatioToSidecar": round(zk / tk, 4),
                                    "ratioOfRatiosAhOverKwh": round((zs / tot) / (zk / tk), 4), "nDrivesCycleBySpeed": new["cycleBySpeedMeta"].get("nDrives"),
                                    "note": "scripted consistency check, not an independent audit: the new Ah accumulator and the long-standing kWh accumulator share the same 1 Hz-grid definition and differ from the sidecar trapezoid (gap-capped) integral by the same ratio (ratio of ratios ~1), so the Ah accumulator adds no discrepancy beyond the pre-existing accumulator-vs-sidecar definition difference"}
dmc = pd.read_csv("drive_master.csv", low_memory=False)
argm = {}
for nm, ccol, acol in (("regen", "regen_peak_Crate", "regen_peak_A"), ("charge peak (dual)", "dual_peak_Crate", "dual_peak_A"), ("engine charge", "eng_charge_peak_Crate", "eng_charge_peak_A")):
    m = dmc[ccol].notna()
    lo, ro = dmc.loc[dmc.loc[m, ccol].idxmax(), "file"], dmc.loc[(dmc.loc[m, acol].abs() / 5.0).idxmax(), "file"]
    argm[nm] = {"legacyArgmaxDrive": lo, "ratedArgmaxDrive": ro, "changed": lo != ro, "legacyMaxC": float(dmc.loc[m, ccol].max()), "ratedMaxC": round(float((dmc.loc[m, acol].abs() / 5.0).max()), 1)}
out["argmaxDrivePerReferenceLine"] = argm
out["otherChanged"] = {"cohortRegenPeakCrateLeaves": 17, "seasonalDriveMasterGtcColumn": "rated-basis gtc since M415 (same column name as the legacy master column; tagged in exposureBasis.tags)",
                       "recordsCRateStrings": "records whose value strings carry (x.xC); see recordsChanged"}
json.dump(out, open(os.path.join("analyses", "M415_method_change", "method_change.json"), "w", encoding="utf-8", newline="\n"), indent=1, default=str)
print(json.dumps({"headline": out["headlinePairs"][:4], "argmax": out["cRateRefLines"]["argmaxDriveChanged"], "nExceed": len(exceed), "cycleBySpeedAh": out["cycleBySpeedAhConsistency"], "nRecordsChanged": len(out["recordsChanged"])}, indent=1))
