"""P-R2 known-answer tests for tools/park_two_state.py (spec analyses/M708_spec.md Rev 2): the 10 s driving traces of a raw drive, the two-state chain against its limits, recovery of known parameters from data generated by the model
itself, and the pre-registered gate rule (gain thresholds, interior parameters, profile narrower than one decade)."""
import os, sys, tempfile
import numpy as np, pandas as pd
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import park_two_state as TS
import restart_census as RC

# --- driving traces from a raw file: probe mean interpolated to the 10 s bin midpoints, I^2 time-weighted per bin
C = RC.COLS
with tempfile.TemporaryDirectory() as td:
    p = os.path.join(td, "20260901_100000.csv")
    h = ["time", C["T1"], C["T2"], C["T3"], C["T4"], "[BMS] HV Battery Current (A)"]
    with open(p, "w", encoding="utf-8", newline="") as f:
        f.write(",".join(h) + "\n")
        for s in range(0, 101):                                    # 101 rows at 1 Hz, T rising 20 -> 30 C on all probes, I = 20 A
            T = 20 + 10 * s / 100.0
            f.write("10:%02d:%02d.000,%s,%s,%s,%s,20\n" % (s // 60, s % 60, T, T, T, T))
    Tp, I2, nb = TS.traces_one(p)
    assert nb == 11 and abs(Tp[0] - (20 + 10 * 5 / 100.0)) < 1e-9 and abs(Tp[5] - (20 + 10 * 55 / 100.0)) < 1e-9, (nb, Tp[:3])
    assert np.allclose(I2[:10], 400.0), I2
    q = os.path.join(td, "20260901_110000.csv")                   # no probe columns -> unavailable
    with open(q, "w", encoding="utf-8", newline="") as f:
        f.write("time,[BMS] HV Battery Current (A)\n11:00:00.000,5\n11:00:01.000,5\n")
    assert TS.traces_one(q) is None

# --- a synthetic fleet of pairs generated BY the two-state chain
rng = np.random.default_rng(11)
N = 70
gap = np.exp(rng.uniform(np.log(0.2), np.log(18), N))
D = pd.DataFrame({"gap_h": gap, "clock0": rng.uniform(0, 24, N), "p_Abar_e": np.full(N, 10.0), "slope": np.zeros(N), "p_amp": np.zeros(N), "p_hpk": np.full(N, 15.0), "x0": rng.uniform(22, 32, N),
                  "y": np.zeros(N), "use": np.ones(N, bool), "day": ["d%d" % (i // 2) for i in range(N)], "gc": "1-4 h", "month": 9})
traces = []
for n in range(N + 1):
    nb = int(rng.integers(20, 60))
    traces.append((np.full(nb, 26.0 + rng.normal(0, 1)), np.full(nb, float(rng.uniform(100, 1500))), nb))
startT = np.r_[24.0, np.zeros(N)]
M = TS.TwoState(D, traces, startT)
true = (8.0, 0.6, 1.0)
alpha, off = 0.004, 0.7
comp = M.chain(*true)
assert np.isfinite(comp).all()
y = comp[:, 0] + alpha * comp[:, 1] + off * comp[:, 2]
M.y = y + rng.normal(0, 0.05, N)
M.startT = np.r_[24.0, M.y]
# limits: no heating and a huge boundary rate -> the probe state returns to the boundary + offset after a long gap
comp_long = TS.TwoState(D.assign(gap_h=500.0), traces, startT).chain(8.0, 0.6, 1.0)
assert np.allclose(comp_long[:, 0], 10.0, atol=1e-6) and np.allclose(comp_long[:, 2], 1.0, atol=1e-6), "long gap: boundary (10 C) and offset coefficient 1"
# the fit recovers the generating parameters
th, b, pr, sse = M.fit(M.use)
assert abs(th[0] - true[0]) / true[0] < 0.25, th
assert abs(b[1] - off) < 0.15 and sse < 0.2, (b, sse)
assert np.sqrt(np.mean((pr - M.y) ** 2)) < 0.12

# --- the pre-registered gate
mk = lambda est, lo, hi: {"est": est, "lo": lo, "hi": hi}
g1 = TS.gate({"1-4 h": mk(0.30, 0.1, 0.5), "<1 h": mk(0.1, -0.1, 0.3)}, True, True)
assert g1["pass"] and g1["classMeetsGain"]["1-4 h"] and not g1["classMeetsGain"]["<1 h"]
assert not TS.gate({"1-4 h": mk(0.30, -0.05, 0.6)}, True, True)["pass"], "the paired interval must exclude zero"
assert not TS.gate({"1-4 h": mk(0.20, 0.1, 0.3)}, True, True)["pass"], "gain below 0.25 C"
assert not TS.gate({"<1 h": mk(0.4, 0.1, 0.7)}, True, True)["pass"] and TS.gate({"<1 h": mk(0.6, 0.1, 1.0)}, True, True)["pass"], "below 1 h needs 0.5 C"
assert not TS.gate({"4-12 h": mk(0.5, 0.2, 0.8)}, False, True)["pass"] and not TS.gate({"4-12 h": mk(0.5, 0.2, 0.8)}, True, False)["pass"], "parameters must be interior and the profile narrower than one decade"
assert TS.gate({"<10 min": mk(1.0, 0.5, 1.5), "all": mk(1.0, 0.5, 1.5)}, True, True)["pass"] is False, "the rule names the pooled below-1-h class and the classes of 1 h or more"
print("test_park_two_state: ok")
